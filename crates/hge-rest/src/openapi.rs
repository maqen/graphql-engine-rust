//! The OpenAPI document of the REST endpoints (`GET /api/swagger/json`), a port of V2's
//! `Hasura.Server.OpenAPI`, built from the same analysis as collection validation.

use std::collections::HashSet;

use async_graphql_parser::types::DocumentOperations;
use async_graphql_value::ConstValue;
use hge_metadata::EndpointMethod;
use hge_schema::model::{Schema, TypeDef, TypeRef};
use serde_json::{Map, Value, json};

use crate::validate::{FieldInfo, Fields, Structure, VarInfo, analyze};
use crate::{Endpoint, RestEndpoints};

/// The OpenAPI 3.0 document for `endpoints` against the admin `schema`.
pub fn openapi(schema: &Schema, endpoints: &RestEndpoints) -> Value {
    let mut builder = Builder {
        schema,
        definitions: Map::new(),
        input_objects: HashSet::new(),
    };
    let mut sorted: Vec<&Endpoint> = endpoints.iter().collect();
    sorted.sort_by(|a, b| (&a.url, &a.name).cmp(&(&b.url, &b.name)));
    let mut paths: Map<String, Value> = Map::new();
    let mut description =
        "This OpenAPI specification is automatically generated by Hasura.".to_owned();
    for endpoint in sorted {
        // V2 keeps a set of methods per endpoint, so a repeated method counts once.
        let mut methods = endpoint.methods.clone();
        methods.sort_by_key(|m| m.as_str());
        methods.dedup();
        for method in methods {
            let (url, operation, messages) = builder.endpoint(endpoint, method);
            if let Some(item) = paths
                .entry(url)
                .or_insert_with(|| json!({}))
                .as_object_mut()
            {
                item.entry(method.as_str().to_ascii_lowercase())
                    .or_insert(operation);
            }
            description.push_str(&messages);
        }
    }
    let mut spec = Map::new();
    spec.insert("openapi".into(), json!("3.0.0"));
    spec.insert(
        "info".into(),
        json!({"title": "Rest Endpoints", "description": description, "version": ""}),
    );
    if !paths.is_empty() {
        spec.insert("paths".into(), Value::Object(paths));
    }
    let mut components = Map::new();
    if !builder.definitions.is_empty() {
        components.insert("schemas".into(), Value::Object(builder.definitions));
    }
    spec.insert("components".into(), Value::Object(components));
    Value::Object(spec)
}

struct Builder<'a> {
    schema: &'a Schema,
    /// `components.schemas`; the first declaration of a name wins.
    definitions: Map<String, Value>,
    /// Input objects (by reference name) already being declared.
    input_objects: HashSet<String>,
}

impl Builder<'_> {
    /// The path, the operation object and the analysis warnings of one endpoint method.
    fn endpoint(&mut self, endpoint: &Endpoint, method: EndpointMethod) -> (String, Value, String) {
        let op = match &endpoint.document.operations {
            DocumentOperations::Single(op) => &op.node,
            DocumentOperations::Multiple(ops) => {
                &ops.values()
                    .next()
                    .expect("resolved endpoints have one")
                    .node
            }
        };
        let (structure, messages) = analyze(self.schema, op, &endpoint.document.fragments);
        let path_segments: Vec<String> = endpoint
            .url
            .split('/')
            .map(|s| match s.strip_prefix(':') {
                Some(var) => format!("{{{var}}}"),
                None => s.to_owned(),
            })
            .collect();
        let url = format!("/api/rest/{}", path_segments.join("/"));
        let mut description = endpoint.comment.clone().unwrap_or_default();
        description.push_str("***\nThe GraphQl query for this endpoint is:\n``` graphql\n");
        description.push_str(&endpoint.query);
        description.push_str("\n```");

        let mut parameters = vec![json!({
            "name": "x-hasura-admin-secret",
            "description": "Your x-hasura-admin-secret will be used for authentication of the API request.",
            "in": "header",
            "schema": {"type": "string"},
        })];
        parameters.extend(self.parameters(&structure, &endpoint.url));

        let mut operation = Map::new();
        operation.insert("summary".into(), json!(endpoint.name));
        operation.insert("description".into(), json!(description));
        operation.insert("parameters".into(), Value::Array(parameters));
        if let Some(body) = self.request_body(method, &structure) {
            operation.insert("requestBody".into(), body);
        }
        let response = json!({
            "content": {"application/json": {"schema": Value::Object(self.selection(&structure.fields))}},
            "description": format!("Responses for {} {url}", method.as_str()),
        });
        operation.insert("responses".into(), json!({ "200": response }));

        let mut warnings = String::new();
        if !messages.is_empty() {
            warnings = format!("\n\nEndpoint \"{}\":", endpoint.name);
            for m in &messages {
                warnings.push_str("\n- ⚠️ ");
                warnings.push_str(m);
            }
        }
        (url, Value::Object(operation), warnings)
    }

    /// One optional parameter per variable of a known scalar type (not a list), by name.
    fn parameters(&self, structure: &Structure, url: &str) -> Vec<Value> {
        let path_vars: Vec<&str> = url.split('/').filter_map(|s| s.strip_prefix(':')).collect();
        let mut vars: Vec<&(String, VarInfo)> = structure.variables.iter().collect();
        vars.sort_by(|a, b| a.0.cmp(&b.0));
        vars.into_iter()
            .filter_map(|(name, var)| {
                let (named, nullable) = match &var.ty {
                    TypeRef::Named(n) => (n, true),
                    TypeRef::NonNull(t) => match t.as_ref() {
                        TypeRef::Named(n) => (n, false),
                        _ => return None,
                    },
                    TypeRef::List(_) => return None,
                };
                if !matches!(self.schema.get(named), Some(TypeDef::Scalar(_))) {
                    return None;
                }
                let (ty, pattern, _) = reference_scalar(named)?;
                let in_path = path_vars.contains(&name.as_str());
                let required = !(nullable || var.default.is_some()) || in_path;
                let mut param = Map::new();
                param.insert("name".into(), json!(name));
                if in_path {
                    param.insert(
                        "description".into(),
                        json!(format!("_\"{name}\" is required as part of the path_")),
                    );
                } else if required {
                    param.insert(
                        "description".into(),
                        json!(format!(
                            "_\"{name}\" is required (enter it either in parameters or request \
                             body)_"
                        )),
                    );
                }
                param.insert("in".into(), json!(if in_path { "path" } else { "query" }));
                param.insert("required".into(), json!(required));
                let mut schema = Map::new();
                if let Some(d) = &var.default {
                    schema.insert("default".into(), const_json(d));
                }
                schema.insert("type".into(), json!(ty));
                if let Some(p) = pattern {
                    schema.insert("pattern".into(), json!(p));
                }
                param.insert("schema".into(), Value::Object(schema));
                Some(Value::Object(param))
            })
            .collect()
    }

    /// A JSON object with one property per variable, for methods that take a body.
    fn request_body(&mut self, method: EndpointMethod, structure: &Structure) -> Option<Value> {
        let takes_body = matches!(
            method,
            EndpointMethod::Post | EndpointMethod::Put | EndpointMethod::Patch
        );
        if structure.variables.is_empty() || !takes_body {
            return None;
        }
        let mut properties = Map::new();
        let mut required = false;
        for (name, var) in &structure.variables {
            let known_scalar = match &var.ty {
                TypeRef::Named(n) => reference_scalar(n).is_some(),
                TypeRef::NonNull(t) => {
                    matches!(t.as_ref(), TypeRef::Named(n) if reference_scalar(n).is_some())
                }
                TypeRef::List(_) => false,
            };
            let optional = var.default.is_some() || !var.ty.is_non_null() || known_scalar;
            required |= !optional;
            let mut schema = self.input_type(&var.ty);
            if let Some(default) = &var.default {
                if let Some(name) = reference_name(&schema) {
                    schema = self.definitions.get(&name).cloned().unwrap_or_default();
                }
                if let Value::Object(s) = &mut schema {
                    s.insert("default".into(), const_json(default));
                }
            }
            properties.insert(name.clone(), schema);
        }
        Some(json!({
            "description": "Query parameters can also be provided in the request body as a JSON object",
            "required": required,
            "content": {"application/json": {"schema": {"type": "object", "properties": properties}}},
        }))
    }

    fn input_type(&mut self, ty: &TypeRef) -> Value {
        self.with_modifiers(ty, &mut |b, name, nullable| match b.schema.get(name) {
            Some(TypeDef::Scalar(_)) => b.scalar(name, nullable),
            Some(TypeDef::Enum(_)) => b.enumeration(name, nullable),
            Some(TypeDef::InputObject(_)) => b.input_object(name, nullable),
            _ => Value::Object(Map::new()),
        })
    }

    fn input_object(&mut self, name: &str, nullable: bool) -> Value {
        let reference = reference_name_of(name, nullable);
        if !self.input_objects.insert(reference.clone()) {
            return ref_to(&reference);
        }
        let Some(TypeDef::InputObject(def)) = self.schema.get(name) else {
            return Value::Object(Map::new());
        };
        let mut properties = Map::new();
        for field in def.fields.values() {
            // V2 leaves out fields whose type is missing from the schema.
            if self.schema.get(field.ty.base()).is_some() {
                properties.insert(field.name.clone(), self.input_type(&field.ty));
            }
        }
        let mut s = Map::new();
        s.insert("title".into(), json!(name));
        if let Some(d) = &def.description {
            s.insert("description".into(), json!(d));
        }
        s.insert("properties".into(), Value::Object(properties));
        s.insert("type".into(), json!("object"));
        s.insert("nullable".into(), json!(nullable));
        self.declare(name, nullable, s)
    }

    /// The schema of a selection set: its properties only.
    fn selection(&mut self, fields: &Fields) -> Map<String, Value> {
        let mut properties = Map::new();
        for (key, info) in fields {
            properties.insert(key.clone(), self.output_field(info));
        }
        let mut s = Map::new();
        if !properties.is_empty() {
            s.insert("properties".into(), Value::Object(properties));
        }
        s
    }

    fn output_field(&mut self, info: &FieldInfo) -> Value {
        match info {
            FieldInfo::Leaf(ty) => {
                self.with_modifiers(ty, &mut |b, name, nullable| match b.schema.get(name) {
                    Some(TypeDef::Enum(_)) => b.enumeration(name, nullable),
                    _ => b.scalar(name, nullable),
                })
            }
            FieldInfo::Object(ty, selection) => {
                self.with_modifiers(ty, &mut |b, name, nullable| {
                    let mut s = b.selection(selection);
                    s.insert("title".into(), json!(name));
                    if let Some(TypeDef::Object(o)) = b.schema.get(name)
                        && let Some(d) = &o.description
                    {
                        s.insert("description".into(), json!(d));
                    }
                    s.insert("type".into(), json!("object"));
                    s.insert("nullable".into(), json!(nullable));
                    Value::Object(s)
                })
            }
        }
    }

    /// V2's `applyModifiers`: lists become inline arrays around the named type's schema.
    fn with_modifiers(
        &mut self,
        ty: &TypeRef,
        named: &mut dyn FnMut(&mut Self, &str, bool) -> Value,
    ) -> Value {
        let (inner, nullable) = match ty {
            TypeRef::NonNull(t) => (t.as_ref(), false),
            other => (other, true),
        };
        match inner {
            TypeRef::Named(n) => named(self, n, nullable),
            TypeRef::List(item) => {
                let items = self.with_modifiers(item, named);
                json!({"nullable": nullable, "type": "array", "items": items})
            }
            TypeRef::NonNull(t) => self.with_modifiers(t, named),
        }
    }

    fn scalar(&mut self, name: &str, nullable: bool) -> Value {
        let mut s = Map::new();
        s.insert("title".into(), json!(name));
        s.insert("nullable".into(), json!(nullable));
        match reference_scalar(name) {
            Some((ty, pattern, inline)) => {
                s.insert("type".into(), json!(ty));
                if let Some(p) = pattern {
                    s.insert("pattern".into(), json!(p));
                }
                if inline {
                    Value::Object(s)
                } else {
                    self.declare(name, nullable, s)
                }
            }
            None => {
                if let Some(TypeDef::Scalar(def)) = self.schema.get(name)
                    && let Some(d) = &def.description
                {
                    s.insert("description".into(), json!(d));
                }
                self.declare(name, nullable, s)
            }
        }
    }

    fn enumeration(&mut self, name: &str, nullable: bool) -> Value {
        let Some(TypeDef::Enum(def)) = self.schema.get(name) else {
            return Value::Object(Map::new());
        };
        let mut s = Map::new();
        s.insert("title".into(), json!(name));
        s.insert("enum".into(), json!(def.values.keys().collect::<Vec<_>>()));
        s.insert("nullable".into(), json!(nullable));
        if let Some(d) = &def.description {
            s.insert("description".into(), json!(d));
        }
        self.declare(name, nullable, s)
    }

    fn declare(&mut self, name: &str, nullable: bool, schema: Map<String, Value>) -> Value {
        let reference = reference_name_of(name, nullable);
        let r = ref_to(&reference);
        self.definitions
            .entry(reference)
            .or_insert(Value::Object(schema));
        r
    }
}

/// Non-null types get their own definition, named with GraphQL's `!` suffix.
fn reference_name_of(name: &str, nullable: bool) -> String {
    if nullable {
        name.to_owned()
    } else {
        format!("{name}!")
    }
}

fn ref_to(reference: &str) -> Value {
    json!({ "$ref": format!("#/components/schemas/{reference}") })
}

fn reference_name(schema: &Value) -> Option<String> {
    schema
        .get("$ref")?
        .as_str()?
        .strip_prefix("#/components/schemas/")
        .map(str::to_owned)
}

/// The OpenAPI type, pattern and whether to inline, for scalars OpenAPI knows (by
/// case-insensitive name).
fn reference_scalar(name: &str) -> Option<(&'static str, Option<&'static str>, bool)> {
    Some(match name.to_ascii_lowercase().as_str() {
        "int" => ("integer", None, true),
        "float" | "double" => ("number", None, true),
        "uuid" => (
            "string",
            Some("[a-f0-9]{8}-[a-f0-9]{4}-4[a-f0-9]{3}-[89aAbB][a-f0-9]{3}-[a-f0-9]{12}"),
            false,
        ),
        "bool" | "boolean" => ("boolean", None, true),
        "string" | "id" => ("string", None, true),
        _ => return None,
    })
}

fn const_json(value: &ConstValue) -> Value {
    value.clone().into_json().unwrap_or(Value::Null)
}
