//! The event trigger metadata API replayed against responses recorded from Hasura V2.
//!
//! `events_api.json` was recorded from `hasura/graphql-engine:v2.51.0-ce` on a fresh
//! database with event delivery paused (no worker runs here either): creating, replacing
//! and deleting triggers with every argument error V2 reports, manual invocation,
//! redelivery, the event and invocation log queries, and the cleanup switches. Rows are
//! given fixed ids and timestamps through `run_sql` so responses are deterministic. It is
//! replayed in order and every response must match exactly, key order included; ids
//! generated by the server (event and trace ids) are compared as placeholders. Steps marked `todo` are known
//! differences: they must still differ, so fixing one means removing its marker.
//!
//! The test runs in a throwaway database on the Postgres server `HASURA_GRAPHQL_DATABASE_URL`
//! points at (see `hge-testdb`); without it the test is skipped.

mod replay;

use replay::post;
use serde_json::json;

#[tokio::test(flavor = "multi_thread")]
async fn event_trigger_api_matches_v2() {
    let Some((_db, router)) = replay::router("events_api").await else {
        return;
    };
    replay::replay(
        &router,
        include_str!("events_api.json"),
        &["00000000-0000-0000-0000-", "10000000-0000-0000-0000-"],
    )
    .await;
    failed_request_leaves_no_sql(&router).await;
}

/// Our own guarantee (V2 does not give it): when a metadata request fails after resolving
/// a new trigger, the trigger's SQL is not left behind in the source.
async fn failed_request_leaves_no_sql(router: &axum::Router) {
    let table = json!({"schema": "public", "name": "ev_t1"});
    let (status, body) = post(
        router,
        "/v1/metadata",
        &json!({"type": "bulk", "args": [
            {"type": "pg_create_event_trigger", "args": {"name": "t9", "table": table,
                "insert": {"columns": "*"}, "webhook": "http://127.0.0.1:1/hook"}},
            {"type": "pg_delete_event_trigger", "args": {"name": "nope"}},
        ]}),
    )
    .await;
    assert_eq!(status, 400, "{body}");
    let (_, rows) = post(
        router,
        "/v2/query",
        &json!({"type": "run_sql", "args": {"sql":
            "SELECT count(*) FROM pg_proc WHERE proname LIKE 'notify_hasura_t9_%'"}}),
    )
    .await;
    assert_eq!(rows["result"][1][0], "0", "{rows}");
}
