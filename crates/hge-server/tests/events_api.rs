//! The event trigger metadata API replayed against responses recorded from Hasura V2.
//!
//! `events_api.json` was recorded from `hasura/graphql-engine:v2.51.0-ce` on a fresh
//! database with event delivery paused (no worker runs here either): creating, replacing
//! and deleting triggers with every argument error V2 reports, manual invocation,
//! redelivery, the event and invocation log queries, and the cleanup switches. Rows are
//! given fixed ids and timestamps through `run_sql` so responses are deterministic. It is
//! replayed in order and every response must match exactly, key order included; ids
//! generated by the server (event and trace ids) are compared as placeholders. Steps marked `todo` are known
//! differences: they must still differ, so fixing one means removing its marker.
//!
//! The database comes from `HASURA_GRAPHQL_DATABASE_URL` (its `hdb_catalog` is dropped
//! first); without it the test is skipped.

use axum::body::Body;
use axum::http::Request;
use hge_server::ServerConfig;
use serde::Deserialize;
use serde_json::{Value, json};
use tower::ServiceExt;

const SCENARIO: &str = include_str!("events_api.json");

#[derive(Deserialize)]
struct Scenario {
    steps: Vec<Step>,
}

#[derive(Deserialize)]
struct Step {
    url: String,
    query: Value,
    status: u16,
    response: Value,
    #[serde(default)]
    todo: Option<String>,
}

/// Replace values the server generates (event ids, trace ids) with placeholders.
fn normalise(v: &Value) -> Value {
    match v {
        Value::String(s) if is_uuid(s) && !is_fixed_id(s) => Value::String("<uuid>".into()),
        Value::Array(items) => Value::Array(items.iter().map(normalise).collect()),
        Value::Object(obj) => Value::Object(
            obj.iter()
                .map(|(k, v)| {
                    let v = match (k.as_str(), v) {
                        ("trace_id" | "span_id", Value::String(_)) => Value::String("<id>".into()),
                        _ => normalise(v),
                    };
                    (k.clone(), v)
                })
                .collect(),
        ),
        other => other.clone(),
    }
}

/// Ids the scenario assigns itself (`00000000-…`, `10000000-…`) are compared as they are.
fn is_fixed_id(s: &str) -> bool {
    s.starts_with("00000000-0000-0000-0000-") || s.starts_with("10000000-0000-0000-0000-")
}

fn is_uuid(s: &str) -> bool {
    s.len() == 36
        && s.bytes().enumerate().all(|(i, c)| match i {
            8 | 13 | 18 | 23 => c == b'-',
            _ => c.is_ascii_hexdigit() && !c.is_ascii_uppercase(),
        })
}

async fn reset_database(url: &str) {
    let (client, conn) = tokio_postgres::connect(url, tokio_postgres::NoTls)
        .await
        .expect("connect to test database");
    tokio::spawn(conn);
    client
        .batch_execute("DROP SCHEMA IF EXISTS hdb_catalog CASCADE")
        .await
        .expect("drop hdb_catalog");
}

async fn post(router: &axum::Router, url: &str, body: &Value) -> (u16, Value) {
    let req = Request::builder()
        .method("POST")
        .uri(url)
        .header("content-type", "application/json")
        .body(Body::from(serde_json::to_vec(body).unwrap()))
        .unwrap();
    let resp = router.clone().oneshot(req).await.unwrap();
    let status = resp.status().as_u16();
    let bytes = axum::body::to_bytes(resp.into_body(), usize::MAX)
        .await
        .unwrap();
    let value = serde_json::from_slice(&bytes)
        .unwrap_or_else(|_| Value::String(String::from_utf8_lossy(&bytes).into_owned()));
    (status, value)
}

#[tokio::test(flavor = "multi_thread")]
async fn event_trigger_api_matches_v2() {
    let Ok(url) = std::env::var("HASURA_GRAPHQL_DATABASE_URL") else {
        eprintln!("HASURA_GRAPHQL_DATABASE_URL not set; skipping end-to-end tests");
        return;
    };
    reset_database(&url).await;
    let config = ServerConfig {
        database_url: Some(url),
        ..ServerConfig::default()
    };
    let engine = hge_server::build_engine(config).await.unwrap();
    let router = hge_server::routes::router(engine);

    let scenario: Scenario = serde_json::from_str(SCENARIO).unwrap();
    let mut failures = vec![];
    for (i, step) in scenario.steps.iter().enumerate() {
        let (status, actual) = post(&router, &step.url, &step.query).await;
        let (actual, expected) = (normalise(&actual), normalise(&step.response));
        // Compare the text so key order counts (`Value` equality ignores it).
        let text = |v: &Value| serde_json::to_string(v).unwrap();
        let matches = status == step.status && text(&actual) == text(&expected);
        match (&step.todo, matches) {
            (None, true) | (Some(_), false) => {}
            (None, false) => failures.push(format!(
                "step {i} {} {}\n  expected ({}): {expected}\n  actual   ({status}): {actual}",
                step.url, step.query, step.status,
            )),
            (Some(todo), true) => failures.push(format!(
                "step {i} now matches V2; remove its todo marker (\"{todo}\")"
            )),
        }
    }
    assert!(
        failures.is_empty(),
        "{} step(s) failed:\n{}",
        failures.len(),
        failures.join("\n")
    );

    failed_request_leaves_no_sql(&router).await;
}

/// Our own guarantee (V2 does not give it): when a metadata request fails after resolving
/// a new trigger, the trigger's SQL is not left behind in the source.
async fn failed_request_leaves_no_sql(router: &axum::Router) {
    let table = json!({"schema": "public", "name": "ev_t1"});
    let (status, body) = post(
        router,
        "/v1/metadata",
        &json!({"type": "bulk", "args": [
            {"type": "pg_create_event_trigger", "args": {"name": "t9", "table": table,
                "insert": {"columns": "*"}, "webhook": "http://127.0.0.1:1/hook"}},
            {"type": "pg_delete_event_trigger", "args": {"name": "nope"}},
        ]}),
    )
    .await;
    assert_eq!(status, 400, "{body}");
    let (_, rows) = post(
        router,
        "/v2/query",
        &json!({"type": "run_sql", "args": {"sql":
            "SELECT count(*) FROM pg_proc WHERE proname LIKE 'notify_hasura_t9_%'"}}),
    )
    .await;
    assert_eq!(rows["result"][1][0], "0", "{rows}");
}
